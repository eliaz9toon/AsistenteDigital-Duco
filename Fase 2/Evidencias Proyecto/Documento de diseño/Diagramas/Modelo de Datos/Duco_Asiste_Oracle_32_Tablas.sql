);

-- Conocimiento administrable
-- CATEGORIAS_FAQ: Categorías de las preguntas frecuentes. [reservada]
CREATE TABLE CATEGORIAS_FAQ (
  ID_CATEGORIA NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  NOMBRE VARCHAR2(100),
  CONSTRAINT PK_CATEGORIAS_FAQ PRIMARY KEY (ID_CATEGORIA)
);

-- PREGUNTAS_FRECUENTES: Respuestas aprobadas que el asistente puede consultar. [en uso]
CREATE TABLE PREGUNTAS_FRECUENTES (
  ID_PREGUNTA NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_CATEGORIA NUMBER(10),
  PREGUNTA VARCHAR2(500),
  RESPUESTA CLOB,
  CONSTRAINT PK_PREGUNTAS_FRECUENTES PRIMARY KEY (ID_PREGUNTA),
  CONSTRAINT FK_PREGUNTAS_FRECUENTES_ID_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS_FAQ(ID_CATEGORIA)
);

-- SINONIMOS_CONSULTA: Variantes de una pregunta aprendidas a partir de las valoraciones. [en uso]
CREATE TABLE SINONIMOS_CONSULTA (
  ID_SINONIMO NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_PREGUNTA NUMBER(10),
  TEXTO VARCHAR2(200),
  CONSTRAINT PK_SINONIMOS_CONSULTA PRIMARY KEY (ID_SINONIMO),
  CONSTRAINT FK_SINONIMOS_CONSULTA_ID_PREGUNTA FOREIGN KEY (ID_PREGUNTA) REFERENCES PREGUNTAS_FRECUENTES(ID_PREGUNTA)
);

-- FAQ_FUENTES: Asociación muchos a muchos entre preguntas frecuentes y sus fuentes. [reservada]
CREATE TABLE FAQ_FUENTES (
  ID_PREGUNTA NUMBER(10) NOT NULL,
  ID_FUENTE NUMBER(10) NOT NULL,
  CONSTRAINT PK_FAQ_FUENTES PRIMARY KEY (ID_PREGUNTA, ID_FUENTE),
  CONSTRAINT FK_FAQ_FUENTES_ID_PREGUNTA FOREIGN KEY (ID_PREGUNTA) REFERENCES PREGUNTAS_FRECUENTES(ID_PREGUNTA),
  CONSTRAINT FK_FAQ_FUENTES_ID_FUENTE FOREIGN KEY (ID_FUENTE) REFERENCES FUENTES_INFORMACION(ID_FUENTE)
);

-- Propuestas de conocimiento creadas por Duco. Solo pasan a las respuestas
-- consultables cuando un administrador las aprueba.
-- PROPUESTAS_CONOCIMIENTO: Respuestas propuestas por Duco. Solo pasan a preguntas frecuentes si un administrador las aprueba. [en uso]
CREATE TABLE PROPUESTAS_CONOCIMIENTO (
  ID_PROPUESTA NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  PREGUNTA VARCHAR2(500) NOT NULL,
  RESPUESTA CLOB NOT NULL,
  ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  FECHA_REVISION TIMESTAMP,
  CONSTRAINT PK_PROPUESTAS_CONOCIMIENTO PRIMARY KEY (ID_PROPUESTA),
  CONSTRAINT CK_PROPUESTAS_CONOCIMIENTO_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADA', 'RECHAZADA'))
);

ALTER TABLE VALORACIONES_RESPUESTA ADD CONSTRAINT FK_VALORACION_FAQ
  FOREIGN KEY (ID_PREGUNTA_FAQ) REFERENCES PREGUNTAS_FRECUENTES(ID_PREGUNTA);
ALTER TABLE VALORACIONES_RESPUESTA ADD CONSTRAINT FK_VALORACION_PROPUESTA
  FOREIGN KEY (ID_PROPUESTA) REFERENCES PROPUESTAS_CONOCIMIENTO(ID_PROPUESTA);
ALTER TABLE VALORACIONES_RESPUESTA ADD CONSTRAINT CK_VALORACION_CONOCIMIENTO
  CHECK (ID_PREGUNTA_FAQ IS NULL OR ID_PROPUESTA IS NULL);

-- Calidad y operación
-- TIPOS_ERROR: Catálogo de tipos de error. [reservada]
CREATE TABLE TIPOS_ERROR (
