-- Experiencias de acciones: un registro por interacción valorada.
-- EXPERIENCIAS_ACCION: Una experiencia por interacción valorada: página, petición y pasos ejecutados (JSON). [en uso]
CREATE TABLE EXPERIENCIAS_ACCION (
 ID_MENSAJE NUMBER PRIMARY KEY REFERENCES MENSAJES(ID_MENSAJE),
 PAGINA VARCHAR2(500 CHAR) NOT NULL,
 PETICION VARCHAR2(2000 CHAR) NOT NULL,
 DATOS CLOB NOT NULL CHECK (DATOS IS JSON),
 FECHA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IX_EXPERIENCIAS_PAGINA ON EXPERIENCIAS_ACCION(PAGINA);
