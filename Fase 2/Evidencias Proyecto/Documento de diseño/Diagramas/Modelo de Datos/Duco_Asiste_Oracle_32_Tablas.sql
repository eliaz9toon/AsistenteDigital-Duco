-- DUCO ASISTE: modelo de datos Oracle IMPLEMENTADO (32 tablas).
-- 30 tablas del diseño original + PROPUESTAS_CONOCIMIENTO y EXPERIENCIAS_ACCION (agregadas durante el desarrollo).
-- Equivale a database/oracle/schema.sql: ya incluye las migraciones 001 a 005 (columnas CLIENT_*_ID, revisión y
-- vínculos de VALORACIONES_RESPUESTA, claves autonuméricas, restricciones y el índice IX_EXPERIENCIAS_PAGINA).
-- Requiere Oracle Database 12c o posterior y un esquema vacío. Ejecutar como DUCO_APP después de create_user.sql.
-- SQL Developer es el cliente, no la base de datos.
-- Cada tabla indica si hoy la aplicación guarda datos en ella (en uso) o si está creada y reservada.

-- Acceso y administración
-- ROLES: Roles de los usuarios administradores. [reservada]
CREATE TABLE ROLES (
  ID_ROL NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  NOMBRE VARCHAR2(60),
  CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL)
);

-- USUARIOS_ADMIN: Personas que administran Duco (nombre, correo y clave con hash). [reservada]
CREATE TABLE USUARIOS_ADMIN (
  ID_ADMIN NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_ROL NUMBER(10),
  NOMBRE VARCHAR2(120),
  CORREO VARCHAR2(180),
  CLAVE_HASH VARCHAR2(255),
  CONSTRAINT PK_USUARIOS_ADMIN PRIMARY KEY (ID_ADMIN),
  CONSTRAINT FK_USUARIOS_ADMIN_ID_ROL FOREIGN KEY (ID_ROL) REFERENCES ROLES(ID_ROL)
);

-- SESIONES_ADMIN: Inicios de sesión de los administradores. [reservada]
CREATE TABLE SESIONES_ADMIN (
  ID_SESION_ADMIN NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_ADMIN NUMBER(10),
  FECHA_INICIO TIMESTAMP,
  CONSTRAINT PK_SESIONES_ADMIN PRIMARY KEY (ID_SESION_ADMIN),
  CONSTRAINT FK_SESIONES_ADMIN_ID_ADMIN FOREIGN KEY (ID_ADMIN) REFERENCES USUARIOS_ADMIN(ID_ADMIN)
);

-- AUDITORIA_CAMBIOS: Registro de los cambios hechos desde la administración (tabla afectada y fecha). [en uso]
CREATE TABLE AUDITORIA_CAMBIOS (
  ID_CAMBIO NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_ADMIN NUMBER(10),
  TABLA_AFECTADA VARCHAR2(80),
  FECHA TIMESTAMP,
  CONSTRAINT PK_AUDITORIA_CAMBIOS PRIMARY KEY (ID_CAMBIO),
  CONSTRAINT FK_AUDITORIA_CAMBIOS_ID_ADMIN FOREIGN KEY (ID_ADMIN) REFERENCES USUARIOS_ADMIN(ID_ADMIN)
);

-- CONFIGURACIONES: Parámetros de configuración en formato clave-valor. [reservada]
CREATE TABLE CONFIGURACIONES (
  ID_CONFIG NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  CLAVE VARCHAR2(80),
  VALOR VARCHAR2(500),
  CONSTRAINT PK_CONFIGURACIONES PRIMARY KEY (ID_CONFIG)
);

-- Chat e inteligencia artificial
-- MODELOS_IA: Modelos de lenguaje utilizados (nombre y proveedor). [reservada]
CREATE TABLE MODELOS_IA (
  ID_MODELO NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  NOMBRE VARCHAR2(100),
  PROVEEDOR VARCHAR2(60),
  CONSTRAINT PK_MODELOS_IA PRIMARY KEY (ID_MODELO)
);

-- VERSIONES_PROMPT: Versiones del prompt del asistente. [reservada]
CREATE TABLE VERSIONES_PROMPT (
  ID_PROMPT NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  TEXTO_PROMPT CLOB,
  VERSION NUMBER(5),
  CONSTRAINT PK_VERSIONES_PROMPT PRIMARY KEY (ID_PROMPT)
);

-- SESIONES_CHAT: Sesiones de chat con interacciones valoradas. CLIENT_SESSION_ID identifica la sesión del navegador. [en uso]
CREATE TABLE SESIONES_CHAT (
  ID_SESION NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  FECHA_INICIO TIMESTAMP,
  ID_MODELO NUMBER(10),
  CLIENT_SESSION_ID VARCHAR2(100),
  CONSTRAINT PK_SESIONES_CHAT PRIMARY KEY (ID_SESION),
  CONSTRAINT UQ_SESIONES_CHAT_CLIENT_ID UNIQUE (CLIENT_SESSION_ID),
  CONSTRAINT FK_SESIONES_CHAT_ID_MODELO FOREIGN KEY (ID_MODELO) REFERENCES MODELOS_IA(ID_MODELO)
);

-- MENSAJES: Mensajes (pregunta y respuesta) de una sesión. CLIENT_MESSAGE_ID identifica el mensaje del navegador. [en uso]
CREATE TABLE MENSAJES (
  ID_MENSAJE NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_SESION NUMBER(10),
  ROL_EMISOR VARCHAR2(20),
  CONTENIDO CLOB,
  FECHA TIMESTAMP,
  CLIENT_MESSAGE_ID VARCHAR2(100),
  CONSTRAINT PK_MENSAJES PRIMARY KEY (ID_MENSAJE),
  CONSTRAINT UQ_MENSAJES_CLIENT_ID UNIQUE (CLIENT_MESSAGE_ID),
  CONSTRAINT FK_MENSAJES_ID_SESION FOREIGN KEY (ID_SESION) REFERENCES SESIONES_CHAT(ID_SESION)
);

-- GENERACIONES_IA: Generaciones del modelo por mensaje (prompt usado y duración). [reservada]
CREATE TABLE GENERACIONES_IA (
  ID_GENERACION NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_MENSAJE NUMBER(10),
  ID_PROMPT NUMBER(10),
  DURACION_MS NUMBER(10),
  CONSTRAINT PK_GENERACIONES_IA PRIMARY KEY (ID_GENERACION),
  CONSTRAINT FK_GENERACIONES_IA_ID_MENSAJE FOREIGN KEY (ID_MENSAJE) REFERENCES MENSAJES(ID_MENSAJE),
  CONSTRAINT FK_GENERACIONES_IA_ID_PROMPT FOREIGN KEY (ID_PROMPT) REFERENCES VERSIONES_PROMPT(ID_PROMPT)
);

-- INTENCIONES: Catálogo de intenciones del usuario. [reservada]
CREATE TABLE INTENCIONES (
  ID_INTENCION NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  NOMBRE VARCHAR2(80),
  DESCRIPCION VARCHAR2(250),
  CONSTRAINT PK_INTENCIONES PRIMARY KEY (ID_INTENCION)
);

-- DETECCIONES_INTENCION: Intención detectada en un mensaje, con su nivel de confianza. [reservada]
CREATE TABLE DETECCIONES_INTENCION (
  ID_DETECCION NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_MENSAJE NUMBER(10),
  ID_INTENCION NUMBER(10),
  CONFIANZA NUMBER(5,4),
  CONSTRAINT PK_DETECCIONES_INTENCION PRIMARY KEY (ID_DETECCION),
  CONSTRAINT FK_DETECCIONES_INTENCION_ID_MENSAJE FOREIGN KEY (ID_MENSAJE) REFERENCES MENSAJES(ID_MENSAJE),
  CONSTRAINT FK_DETECCIONES_INTENCION_ID_INTENCION FOREIGN KEY (ID_INTENCION) REFERENCES INTENCIONES(ID_INTENCION)
);

-- VALORACIONES_RESPUESTA: Valoración (👍/👎) de una respuesta, una por mensaje, con estado de revisión y vínculo a la pregunta frecuente o propuesta correspondiente. [en uso]
CREATE TABLE VALORACIONES_RESPUESTA (
  ID_VALORACION NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  ID_MENSAJE NUMBER(10),
  ID_PREGUNTA_FAQ NUMBER(10),
  ID_PROPUESTA NUMBER(10),
  PUNTUACION NUMBER(2),
  ESTADO_REVISION VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  CONSTRAINT PK_VALORACIONES_RESPUESTA PRIMARY KEY (ID_VALORACION),
  CONSTRAINT UQ_VALORACIONES_RESPUESTA_MENSAJE UNIQUE (ID_MENSAJE),
  CONSTRAINT CK_VALORACIONES_ESTADO_REVISION CHECK (ESTADO_REVISION IN ('PENDIENTE', 'REVISADA')),
  CONSTRAINT FK_VALORACIONES_RESPUESTA_ID_MENSAJE FOREIGN KEY (ID_MENSAJE) REFERENCES MENSAJES(ID_MENSAJE)
);

-- Contenido y navegación
