-- REGISTROS_ERROR: Errores ocurridos en una sesión de chat. [reservada]
CREATE TABLE REGISTROS_ERROR (
  ID_ERROR NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
