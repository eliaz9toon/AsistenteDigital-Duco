CREATE TABLE PROPUESTAS_CONOCIMIENTO (
  ID_PROPUESTA NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  PREGUNTA VARCHAR2(500) NOT NULL,
  RESPUESTA CLOB NOT NULL,
  ESTADO VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  FECHA_REVISION TIMESTAMP,
  CONSTRAINT PK_PROPUESTAS_CONOCIMIENTO PRIMARY KEY (ID_PROPUESTA),
  CONSTRAINT CK_PROPUESTAS_CONOCIMIENTO_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADA', 'RECHAZADA'))
)
